
from pydantic import BaseModel


class AnalysisResult(BaseModel):
    """
    Represents the business analysis generated by the LLM.
    """

    summary: str

    insights: list[str]

    @property
    def key_findings(self) -> list[str]:
        """
        Backward-compatible alias for older code and tests.

        The current API uses `insights`.
        Older code can continue accessing:
        
            result.key_findings
        """
        return self.insights

